export function getStaticPhraseMap(locale: Locale): Map<string, string> {
  const map = new Map<string, string>();
  for (const phrase of staticPhrases) {
    map.set(phrase.en, phrase[locale]);
    map.set(phrase.ar, phrase[locale]);
    map.set(phrase.sv, phrase[locale]);
  }
  for (const key of Object.keys(translations.en) as TranslationKey[]) {
    const values = {
      en: translations.en[key],
      ar: translations.ar[key],
      sv: translations.sv[key],
    };
    map.set(values.en, values[locale]);
    map.set(values.ar, values[locale]);
    map.set(values.sv, values[locale]);
  }
  return map;
}
